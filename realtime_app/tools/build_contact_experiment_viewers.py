def read_json(path):
    return json.loads(path.read_text(encoding='utf-8'))


def add_observations(payload, metadata, target):
    from pose_app.body_observations import load_ordered_predictions as _load_predictions
    inputs, ids = metadata['raw_inputs'], payload['frameIds']
    body = np.stack([_load_predictions(Path(inputs[f'{side}_predictions']), side) for side in ['left', 'right']], axis=1)
    source = read_json(Path(read_json(OUT / 'toe_direction_prefix/protocol.json')['source_body_run']) / 'run_parameters.json')
    body[0] = np.asarray(read_json(Path(source['first_frame_observations']))['keypoints'])
    payload['observedPixels'] = finite(body[ids, ..., :2])
    toes = np.full((62, 2, 4, 2), np.nan)
    for view, (side, rotation) in enumerate([('left', 'ccw90'), ('right', 'cw90')]):
        for i, line in enumerate((DETECTOR / f'{side}_sapiens_raw.jsonl').read_text(encoding='utf-8').splitlines()[:62]):
            row = json.loads(line)
            if row['pair_id'] != i or row['file_name'] != f'pair_{i:04d}.png':
                raise ValueError('Toe/raw source identities differ')
            if row['instances']:
                for k, idx in enumerate(TOE_INDICES):
                    toes[i, view, k] = model_to_raw_point(*row['instances'][0]['keypoints308'][idx], 1920, 1080, rotation)
    payload['toeObservedPixels'] = finite(toes[ids])
    pairs = Path(inputs['input_pairs'])
    payload['images'] = [[Path(os.path.relpath(pairs / folder / f'pair_{i:04d}.png', target)).as_posix() for folder in ['left_ccw90', 'right_cw90']] for i in ids]
    from pose_app.fisheye_camera import load_stereo_fisheye
    return load_stereo_fisheye(inputs['calibration_dir'])


def model_extras(entry, result, ids, shared, cal, details):
    # Source mesh parameters generated by export; reconstruct toe/ball points
    # from that SAME already-exported real mesh, not another run's web vertices.
    import base64
    mesh_world = np.frombuffer(base64.b64decode(entry['mesh']), dtype=np.float32).reshape(len(ids), 6890, 3)
    scene = np.load(shared / 'scene/scene_transforms.npz')
    rotation = scene['rotation_ground_from_left'][ids]
    translation = scene['translation_ground_from_left_mm'][ids]/1000
    toe_camera = np.einsum('tji,tkj->tki', rotation, mesh_world[:, TOE_VERTICES]-translation[:, None])
    entry['toePixels'] = finite(project(toe_camera, cal))
    ball_mm = np.stack([mesh_world[:, SURFACE[indices], 2].min(axis=1)*1000 for indices in BALL], axis=1)
    labels = support_labels()
    entry['contactInfo'] = [f"支撑假设 L/R：{labels[i].astype(int).tolist()}；ball最低 L/R：{ball_mm[k, 0]:.2f} / {ball_mm[k, 1]:.2f} mm\n{details[k]}" for k, i in enumerate(ids)]
    entry['sourceResult'] = result


def write_page(payload, metadata, target, static):
    payload.update(static=static, comparison=True)
    raw = json.dumps(payload, ensure_ascii=False, allow_nan=False, separators=(',', ':')).encode()
    compressed = gzip.compress(raw)
    (target / 'data.json.gz').write_bytes(compressed)
    templates = APP / 'walker_tools/visualization'
    html = (templates / 'smplh_repair_comparison.html').read_text(encoding='utf-8')
    style = '.projections{position:absolute;right:12px;bottom:12px;z-index:3;background:#fffef7f5;border:1px solid #bbc5be;border-radius:6px;max-width:min(650px,52vw)}.scene:has(.projections[open])>#scene{width:46%}.projections>summary{padding:8px}.projections>div{padding:8px}.projections p{font-size:11px;margin:4px 0}.imagePair{display:flex;gap:5px}.imagePair canvas{width:50%;height:auto;max-height:60vh;object-fit:contain;background:#fff}nav{display:flex;gap:10px;font-size:12px}nav a{color:#355f52}'
    html = html.replace('</style>', style + '</style>').replace('修正后候选', '工程对照，保留未通过结果')
    nav = '<nav><a href="../sequences/index.html?frame=55">62帧序列</a><a href="../matched/index.html?frame=55">同先验静态</a><a href="../expressibility/index.html?frame=55">局部旋转诊断</a></nav>'
    html = html.replace('<h1>人体运动</h1>', '<h1>接触试验</h1>'+nav)
    (target / 'index.html').write_text(html, encoding='utf-8')
    (target / 'viewer.js').write_text((templates / 'smplh_minimal_view.js').read_text(encoding='utf-8'), encoding='utf-8')
    accepted = np.asarray(payload['accepted'])
    import base64
    raw_points = np.frombuffer(base64.b64decode(payload['raw']), dtype=np.float32).reshape(len(accepted), 17, 3)
    available = np.isfinite(raw_points).all(axis=-1)
    metadata.update(frames=payload['frames'], frame_ids=payload['frameIds'], static_independent_samples=static,
        variants=[{'name': m['name'], 'label': m['label'], 'source_result': m['sourceResult']} for m in payload['models']],
        per_joint_raw_finite=available.sum(axis=0).tolist(), per_joint_strict_accepted=accepted.sum(axis=0).tolist(),
        per_joint_raw_finite_rejected=(available & ~accepted).sum(axis=0).tolist(),
        per_frame_rejection_reasons=payload['rawReasons'], payload_bytes=len(compressed), page=str(target / 'index.html'),
        browser_status='pending', original_images_reprojection=True, no_static_interpolation=True)
    save(target / 'metadata.json', metadata)
    print('saved', target, 'variants', len(payload['models']), 'frames', payload['frameIds'], flush=True)


def build(kind):
    target = SHARED / kind
    target.mkdir(parents=True, exist_ok=True)
    if any(target.iterdir()):
        raise FileExistsError(f'Populated output must not be overwritten: {target}')
    baseline = np.load(OUT / 'toe_direction_prefix/result.npz')
    shared_summary = None
    if kind == 'sequences':
        variants = [('toe_direction_prefix', '原方向版', '研究基线；未证明真实接触'),
            ('soft_contact_prefix', '有限差分＋软接触', '未通过：方向与收敛退化'),
            ('toe_direction_autograd_prefix', '自动导数·无接触', '未通过：身体残差与下穿退化'),
            ('soft_contact_autograd_prefix', '自动导数＋软接触', '未通过：下穿与整体门')]
        ids = np.arange(62)
    elif kind == 'matched':
        ids = np.array([40, 55, 61])
        shared_summary = read_json(OUT / 'contact_matched_prior_feasibility/summary.json')
        candidates = np.load(OUT / 'contact_matched_prior_feasibility/candidates.npz')
        variants = [('baseline', '原方向版（对应帧）', '研究基线'), ('finite_soft_contact', '同先验·差分软接触', '仅独立静态求解'),
            ('autograd_soft_contact', '同先验·自动软接触', '仅独立静态求解'), ('constrained_original_map', '同先验·几何接触', '40通过；55/61未通过，非连续轨迹')]
    else:
        ids = np.array([35, 40, 47, 55, 61])
        shared_summary = read_json(OUT / 'contact_expressibility_complete/summary.json')
        candidates = np.load(OUT / 'contact_expressibility_complete/static_poses.npz')
        variants = [('baseline', '原方向版（对应帧）', '研究基线'), ('latent_data_only', '局部latent·无接触', '静态诊断，无时序/latent先验'),
            ('latent_contact', '局部latent＋接触', '未通过；仅静态诊断'), ('so3_data_only', '局部SO(3)·无接触', '未通过；无先验静态上限'),
            ('so3_contact', '局部SO(3)＋接触', '未通过：大幅扭脚/下穿/方向退化')]
    merged, checks = None, []
    for name, label, rejection in variants:
        result, rows, details = None, None, []
        if kind == 'sequences':
            array = np.load(OUT / name / 'result.npz')
            track = [json.loads(line) for line in (OUT / name / 'trajectory.jsonl').read_text(encoding='utf-8').splitlines()]
            details = [f"原帧求解：{r['optimizer']['status']}；接触启用：{r.get('contact_active', False)}；足方向使用项：{np.sum(r.get('toe_used', []))}" for r in track]
            result_path = str(OUT / name / 'result.npz')
        else:
            array = {key: baseline[key][ids] for key in ['transl', 'root_rotation', 'body_rotations', 'predicted_coco', 'timestamp_s']}
            array.update(betas=baseline['betas'], regressor=baseline['regressor'])
            rows = []
            for k, frame in enumerate(ids):
                report = shared_summary[str(frame)]['saved_direction_baseline' if kind == 'matched' and name == 'baseline' else 'baseline' if name == 'baseline' else name]
                if name != 'baseline':
                    prefix = f'{frame}_{name}_'
                    array['body_rotations'][k] = candidates[prefix+'body_rotations']
                    array['predicted_coco'][k] = candidates[prefix+'coco_m'][:17]
                    if kind == 'matched':
                        array['transl'][k] = candidates[prefix+'transl']; array['root_rotation'][k] = candidates[prefix+'root_rotation']
                solver = report.get('solver', {})
                status = solver.get('status', 'static_diagnostic')
                if not isinstance(status, str):
                    status = 'static_success' if solver.get('success') else 'static_unconverged'
                if kind == 'expressibility' and name != 'baseline':
                    status = 'converged' if solver['optimality'] <= .05 else 'feasible_unconverged'
                rows.append({'optimizer': {'status': status, 'termination': solver.get('termination', solver.get('message', '保存姿态，非时序跟踪'))}})
                details.append('本帧门：'+str(report.get('gates', '基线'))+'\n原始报告保留；本页不估计导数/新后验。')
            result, result_path = array, str(OUT / ('contact_matched_prior_feasibility/candidates.npz' if kind == 'matched' else 'contact_expressibility_complete/static_poses.npz'))
        payload, metadata = export('toe_direction_prefix' if kind != 'sequences' else name, label, rejection, SHARED,
            target=target, result_override=result, rows_override=rows, frame_ids=ids, write_page=False)
        if merged is None:
            merged = payload; cal = add_observations(merged, metadata, target)
        entry = payload['models'][0]
        entry['name'] = name
        model_extras(entry, result_path, ids, SHARED, cal, details)
        if merged is not payload:
            merged['models'].append(entry)
        checks.append(metadata['geometry_max_difference_m'])
    merged['title'] = {'sequences': '接触对照 · 62帧', 'matched': '同先验接触 · 三个独立帧', 'expressibility': '局部旋转 · 五个独立帧'}[kind]
    fresh = np.load(SHARED / 'scene/scene_transforms.npz')
    frame0_hips = baseline['predicted_coco'][0, 11:13] @ fresh['rotation_ground_from_left'][0].T + fresh['translation_ground_from_left_mm'][0]/1000
    merged['center'] = np.median(frame0_hips[:, :2], axis=0).tolist()
    merged['rejection'] = '工程候选未通过整体门；参考地面非独立真值'
    metadata['geometry_checks_per_variant_m'] = checks
    metadata['source_results'] = [entry['sourceResult'] for entry in merged['models']]
    write_page(merged, metadata, target, kind != 'sequences')


